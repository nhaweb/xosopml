export function foldVietnamese(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase();
}

export function dreamInitial(keyword: string): string {
  const folded = foldVietnamese(keyword).replace(/[^a-z]/g, '');
  return (folded[0] ?? '#').toUpperCase();
}
